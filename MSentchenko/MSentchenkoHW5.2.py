# Задача №1
#
# Дан список:
# l = [9, 2, 6, 4, 5, 12, 7, 8, 6]
# необходимо вывести сумму всех значений.

print('Результат задачи 1')
l = [9, 2, 6, 4, 5, 12, 7, 8, 6]
total = 0
for num in l:
    total += num
print(total, end=' ')
print('\nКонец задачи 1')
