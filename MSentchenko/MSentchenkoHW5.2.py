# # Задача №2
# #
# # Дан список:
# # l = [9, 2, 6, 4, 5, 12, 7, 8, 6]
# # необходимо вывести максимальное значение.
print('Результат задачи 2')
l = [9, 2, 6, 4, 5, 12, 7, 8, 6]
value = l[0]
for num in l:
    if num > value:
        value = num
        print(value, end=' ')
print('\nКонец задачи 2')

