# Задача №4
#
# Дан список:
# l = [1, 2, 3, 4, 5, 6, 7, 8, 9]
# необходимо вывести среднее арифметическое всех значений.
print('Результат задачи 4')
l = [1, 2, 3, 4, 5, 6, 7, 8, 9]
count = len(l)
total = 0
for num in l:
    total += num
average = total / count
print(average, end=' ')
print('\nКонец задачи 4')
